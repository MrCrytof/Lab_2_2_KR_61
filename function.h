#include <stdio.h>
#include <stdlib.h>
#include <math.h>

#ifndef FUNCTION_H
#define FUNCTION_H

/**
 * @brief Обчислює значення підінтегральної функції f(x).
 *
 * @details Для варіанта №7 підінтегральна функція має вигляд:
 *          f(x) = x^2 * sqrt(1 + x^3).
 *
 * @param x Аргумент функції.
 *
 * @return Обчислене значення f(x).
 */
double integrandFunction(double x);


/**
 * @brief Обчислює визначений інтеграл методом лівих прямокутників.
 *
 * @details Інтервал [a, b] ділиться на n рівних проміжків.
 *          Для кожного проміжку використовується значення
 *          функції в його лівій кінцевій точці.
 *
 * @param a Нижня межа інтегрування.
 * @param b Верхня межа інтегрування.
 * @param n Кількість проміжків розбиття.
 *
 * @return Наближене значення визначеного інтеграла.
 */
double leftRectangles(double a, double b, int n);


/**
 * @brief Обчислює визначений інтеграл методом правих прямокутників.
 *
 * @details Інтервал [a, b] ділиться на n рівних проміжків.
 *          Для кожного проміжку використовується значення
 *          функції в його правій кінцевій точці.
 *
 * @param a Нижня межа інтегрування.
 * @param b Верхня межа інтегрування.
 * @param n Кількість проміжків розбиття.
 *
 * @return Наближене значення визначеного інтеграла.
 */
double rightRectangles(double a, double b, int n);


/**
 * @brief Обчислює визначений інтеграл методом трапецій.
 *
 * @details Інтервал [a, b] ділиться на n рівних проміжків.
 *          Площа під графіком функції апроксимується
 *          сумою площ трапецій.
 *
 * @param a Нижня межа інтегрування.
 * @param b Верхня межа інтегрування.
 * @param n Кількість проміжків розбиття.
 *
 * @return Наближене значення визначеного інтеграла.
 */
double trapezoids(double a, double b, int n);


/**
 * @brief Обчислює визначений інтеграл методом Сімпсона.
 *
 * @details Інтервал [a, b] ділиться на n рівних проміжків.
 *          Функція апроксимується параболами.
 *          Кількість проміжків n повинна бути парною.
 *
 * @param a Нижня межа інтегрування.
 * @param b Верхня межа інтегрування.
 * @param n Парна кількість проміжків розбиття.
 *
 * @return Наближене значення визначеного інтеграла.
 */
double simpson(double a, double b, int n);


/**
 * @brief Зчитує дійсне число з клавіатури.
 *
 * @details Введене значення зчитується як рядок та перетворюється
 *          у число типу double. Некоректне введення відхиляється,
 *          після чого користувачеві пропонується повторити введення.
 *
 * @param message Повідомлення, яке виводиться перед введенням.
 *
 * @return Коректне дійсне число, введене користувачем.
 */
double readDouble(const char *message);


/**
 * @brief Зчитує додатне ціле число з клавіатури.
 *
 * @details Перевіряє, що введене значення є додатним цілим числом
 *          та знаходиться в допустимому діапазоні.
 *
 * @param message Повідомлення, яке виводиться перед введенням.
 *
 * @return Коректне додатне ціле число.
 */
int readPositiveInt(const char *message);


/**
 * @brief Обчислює визначений інтеграл вибраним методом.
 *
 * @details Вибір методу виконується за номером:
 *
 *          1 — метод лівих прямокутників;
 *          2 — метод правих прямокутників;
 *          3 — метод трапецій;
 *          4 — метод Сімпсона.
 *
 * @param a Нижня межа інтегрування.
 * @param b Верхня межа інтегрування.
 * @param n Кількість проміжків розбиття.
 * @param method Номер вибраного методу.
 *
 * @return Наближене значення визначеного інтеграла.
 *         У разі некоректного номера методу повертає 0.0.
 */
double calculateIntegral(
    double a,
    double b,
    int n,
    int method
);


/**
 * @brief Знаходить необхідну кількість проміжків для заданої точності.
 *
 * @details Обчислює інтеграл для n та n + 2 проміжків
 *          і порівнює отримані результати.
 *          Розрахунок повторюється доти, доки різниця
 *          між результатами не перевищить epsilon.
 *
 * @param a Нижня межа інтегрування.
 * @param b Верхня межа інтегрування.
 * @param epsilon Допустима похибка.
 * @param method Номер вибраного методу інтегрування.
 * @param integralValue Вказівник для збереження значення інтеграла.
 *
 * @return Необхідна кількість проміжків.
 */
int findRequiredN(
    double a,
    double b,
    double epsilon,
    int method,
    double *integralValue
);


/**
 * @brief Виводить результат чисельного інтегрування.
 *
 * @details Виводить назву методу, межі інтегрування,
 *          кількість проміжків та отримане значення інтеграла.
 *
 * @param methodName Назва методу чисельного інтегрування.
 * @param a Нижня межа інтегрування.
 * @param b Верхня межа інтегрування.
 * @param n Кількість проміжків розбиття.
 * @param result Обчислене значення інтеграла.
 */
void printResult(
    const char *methodName,
    double a,
    double b,
    int n,
    double result
);

#endif /* FUNCTION_H */